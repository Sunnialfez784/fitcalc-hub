function ex(
  exerciseId: string,
  sets: number,
  reps: string,
  restSec: number,
  sortOrder: number,
  notes?: string,
): WorkoutExerciseItem {
  return { exerciseId, sets, reps, restSec, sortOrder, notes, tempo: "3-1-1-0" };
}

function day(
  dayNumber: number,
  title: string,
  focus: string,
  exercises: WorkoutExerciseItem[],
  planSlug?: string,
): WorkoutDay {
  return { dayNumber, title, focus, isRestDay: false, exercises, planSlug };
}

function rest(dayNumber: number): WorkoutDay {
  return {
    dayNumber,
    title: "Rest / Active Recovery",
    focus: "Recovery",
    isRestDay: true,
    exercises: [],
    notes: "Walk, mobility, or light cardio under 30 minutes.",
  };
}

