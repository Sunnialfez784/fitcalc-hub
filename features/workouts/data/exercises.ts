export const SAMPLE_EXERCISES: Exercise[] = SEEDS.map((s, i) => {
  const slug = slugify(s.name);
  return {
    id: `ex-${slug}`,
    name: s.name,
    slug,
    description: `${s.name} targets the ${s.primary.replace("-", " ")} with controlled technique and progressive overload.`,
    primaryMuscle: s.primary,
    secondaryMuscles: s.secondary ?? [],
    difficulty: s.difficulty ?? "BEGINNER",
    equipment: s.equipment,
    exerciseType: s.type ?? "compound",
    instructions: [
      "Set up with stable footing and braced core.",
      "Move through a full controlled range of motion.",
      "Pause briefly in the stretched or contracted position as appropriate.",
      "Return under control without bouncing.",
    ],
    commonMistakes: [
      "Using momentum instead of muscle tension.",
      "Cutting the range of motion short.",
      "Letting the lower back round under load.",
    ],
    tips: ["Film a set from the side to check form.", "Add load only when all reps are clean."],
    benefits: [
      `Strengthens ${s.primary.replace("-", " ")}`,
      "Supports balanced physique development",
      "Transfers to daily movement and sport",
    ],
    defaultSets: s.sets ?? 3,
    defaultReps: s.reps ?? "8-12",
    defaultRestSec: s.rest ?? 90,
    tempo: "3-1-1-0",
    caloriesPerMinute: s.cal ?? 6,
    videoUrl: undefined,
    imageGradient: GRADIENTS[i % GRADIENTS.length],
    published: true,
  };
});

export function getExerciseMap() {
  return new Map(SAMPLE_EXERCISES.map((e) => [e.id, e]));
}
